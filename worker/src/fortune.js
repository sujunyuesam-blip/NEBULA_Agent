export function dayKey() {
  return new Date().toISOString().slice(0, 10);
}

// 稳定抽取：user+day 哈希
function hashStr(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
}

export async function drawFortune(env, userId) {
  const day = dayKey();
  const existing = await env.DB.prepare("SELECT fortune_id FROM fortunes WHERE user_id = ? AND day = ?").bind(userId, day).first();
  let fid;
  if (existing) {
    fid = existing.fortune_id;
  } else {
    fid = hashStr(`${userId}:${day}`) % FORTUNES.length;
    await env.DB.prepare(
      "INSERT INTO fortunes (user_id, day, fortune_id, created_at) VALUES (?, ?, ?, ?)"
    ).bind(userId, day, fid, nowSec()).run();
  }
  const fortune = FORTUNES[fid];
  return {
    ...fortune,
    day,
    redrawn: false,
    yiBasis: BASIS[fortune.yi] || "",
    jiBasis: BASIS[fortune.ji] || "",
    note: "本签文融合传统黄历文化与学习科学，仅供娱乐与自我激励",
  };
}

